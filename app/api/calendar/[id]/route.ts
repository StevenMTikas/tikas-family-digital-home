// Single-event API. See docs/02_Modules/Calendar.md: "Editing restricted to
// creator + admins" — being an assigned participant does not grant edit rights.
//
// Recurrence: a recurring Event is a set of independent rows sharing
// `recurrence_id`. PATCH/DELETE accept an editScope/scope of "this"
// (default), "future" (this row + every later row in the series), or
// "series" (every row in the series, past and future) — see
// lib/core/recurrence.ts's header comment for the generation model this
// plugs into. Known limitation: deleting "this occurrence" on the single
// farthest-out generated occurrence of an active series can be
// regenerated by the next scheduler tick, since there's no tombstone for
// a skipped date — narrow in practice since the generator keeps ~3
// months of occurrences filled in ahead of time, but documented in
// Calendar.md/Tasks.md rather than solved with a full exception-date
// system for MVP.

import { NextRequest, NextResponse } from "next/server";
import { getDb } from "@/db/client";
import { getAuthUser, canManageUser } from "@/lib/core/permissions";
import type { RecurrenceFrequency } from "@/lib/core/recurrence";

function errorResponse(code: string, message: string, status: number) {
  return NextResponse.json({ error: { code, message } }, { status });
}

const EVENT_CATEGORIES = ["Budget", "Home Repair", "Chores", "Medical", "School", "Social/Family"] as const;
type EventCategory = (typeof EVENT_CATEGORIES)[number];

interface EventRow {
  id: string;
  title: string;
  description: string | null;
  date_time: string;
  created_by: string;
  visibility: "public" | "private";
  category: EventCategory | null;
  reminder_lead_time: string | null;
  recurrence_id: string | null;
  recurrence_frequency: RecurrenceFrequency | null;
}

function getAssigneeIds(eventId: string): string[] {
  return (
    getDb().prepare(`SELECT user_id FROM event_assignments WHERE event_id = ?`).all(eventId) as {
      user_id: string;
    }[]
  ).map((row) => row.user_id);
}

function toEventResponse(row: EventRow) {
  return {
    id: row.id,
    title: row.title,
    description: row.description,
    dateTime: row.date_time,
    visibility: row.visibility,
    category: row.category,
    reminderLeadTime: row.reminder_lead_time,
    recurrenceId: row.recurrence_id,
    recurrenceFrequency: row.recurrence_frequency,
    createdBy: row.created_by,
    assigneeIds: getAssigneeIds(row.id),
  };
}

async function loadEventForEdit(id: string, actorId: string | null) {
  const actor = actorId ? await getAuthUser(actorId) : null;
  if (!actor) return { error: errorResponse("UNAUTHENTICATED", "Login required.", 401) } as const;

  const row = getDb().prepare(`SELECT * FROM events WHERE id = ?`).get(id) as EventRow | undefined;
  if (!row) return { error: errorResponse("NOT_FOUND", "No such event.", 404) } as const;

  if (!canManageUser(actor, row.created_by)) {
    return {
      error: errorResponse("FORBIDDEN", "Only the event's creator or an admin can change it.", 403),
    } as const;
  }

  return { row } as const;
}

type Scope = "this" | "future" | "series";

function parseScope(value: unknown): Scope {
  return value === "future" || value === "series" ? value : "this";
}

export async function PATCH(req: NextRequest, { params }: { params: Promise<{ id: string }> }) {
  const { id } = await params;
  const result = await loadEventForEdit(id, req.headers.get("x-user-id"));
  if ("error" in result) return result.error;
  const target = result.row;

  const body = await req.json().catch(() => null);
  const db = getDb();

  const editScope = parseScope(body?.editScope);
  const applyToSeries = target.recurrence_id !== null && editScope !== "this";

  // Safe to apply across a whole series — never date_time, which only ever
  // moves the single occurrence being edited (there's no single "date" a
  // bulk edit across different-dated future occurrences could mean).
  const seriesUpdates: Record<string, unknown> = {};
  if (typeof body?.title === "string" && body.title.trim()) seriesUpdates.title = body.title.trim();
  if (typeof body?.description === "string" || body?.description === null) {
    seriesUpdates.description = body.description;
  }
  if (body?.visibility === "public" || body?.visibility === "private") {
    seriesUpdates.visibility = body.visibility;
  }
  if (body?.category === null || EVENT_CATEGORIES.includes(body?.category)) {
    seriesUpdates.category = body.category;
  }
  if (typeof body?.reminderLeadTime === "string" || body?.reminderLeadTime === null) {
    seriesUpdates.reminder_lead_time = body.reminderLeadTime;
  }

  const dateTimeUpdate = typeof body?.dateTime === "string" && body.dateTime ? body.dateTime : undefined;
  const fields = Object.keys(seriesUpdates);
  const assigneeIds = Array.isArray(body?.assigneeIds)
    ? (body.assigneeIds.filter((v: unknown) => typeof v === "string") as string[])
    : undefined;

  if (fields.length === 0 && !assigneeIds && !dateTimeUpdate) {
    return errorResponse("INVALID_INPUT", "No changes provided.", 400);
  }
  if (assigneeIds && assigneeIds.length === 0) {
    return errorResponse("INVALID_INPUT", "At least one assignee is required.", 400);
  }

  const targetIds: string[] = applyToSeries
    ? (
        editScope === "future"
          ? (db
              .prepare(`SELECT id FROM events WHERE recurrence_id = ? AND date_time >= ?`)
              .all(target.recurrence_id, target.date_time) as { id: string }[])
          : (db.prepare(`SELECT id FROM events WHERE recurrence_id = ?`).all(target.recurrence_id) as {
              id: string;
            }[])
      ).map((r) => r.id)
    : [id];

  const update = db.transaction(() => {
    if (fields.length > 0) {
      const setClause = fields.map((f) => `${f} = @${f}`).join(", ");
      const stmt = db.prepare(`UPDATE events SET ${setClause} WHERE id = @id`);
      for (const targetId of targetIds) stmt.run({ ...seriesUpdates, id: targetId });
    }
    if (dateTimeUpdate) {
      db.prepare(`UPDATE events SET date_time = ? WHERE id = ?`).run(dateTimeUpdate, id);
    }
    if (assigneeIds) {
      const deleteStmt = db.prepare(`DELETE FROM event_assignments WHERE event_id = ?`);
      const insertAssignment = db.prepare(`INSERT INTO event_assignments (event_id, user_id) VALUES (?, ?)`);
      for (const targetId of targetIds) {
        deleteStmt.run(targetId);
        for (const userId of assigneeIds) insertAssignment.run(targetId, userId);
      }
    }
  });
  update();

  const row = db.prepare(`SELECT * FROM events WHERE id = ?`).get(id) as EventRow;
  return NextResponse.json(toEventResponse(row));
}

export async function DELETE(req: NextRequest, { params }: { params: Promise<{ id: string }> }) {
  const { id } = await params;
  const result = await loadEventForEdit(id, req.headers.get("x-user-id"));
  if ("error" in result) return result.error;
  const target = result.row;

  const scope = parseScope(req.nextUrl.searchParams.get("scope"));
  const db = getDb();

  const targetIds: string[] =
    target.recurrence_id && scope !== "this"
      ? (
          scope === "future"
            ? (db
                .prepare(`SELECT id FROM events WHERE recurrence_id = ? AND date_time >= ?`)
                .all(target.recurrence_id, target.date_time) as { id: string }[])
            : (db.prepare(`SELECT id FROM events WHERE recurrence_id = ?`).all(target.recurrence_id) as {
                id: string;
              }[])
        ).map((r) => r.id)
      : [id];

  const del = db.transaction(() => {
    const placeholders = targetIds.map(() => "?").join(",");
    db.prepare(`DELETE FROM event_assignments WHERE event_id IN (${placeholders})`).run(...targetIds);
    db.prepare(`DELETE FROM events WHERE id IN (${placeholders})`).run(...targetIds);

    // "This and future": cap the series at the deletion boundary so the
    // scheduler's rolling-window top-up doesn't regenerate what was just
    // removed — only meaningful if earlier occurrences still remain.
    if (scope === "future" && target.recurrence_id) {
      const remaining = db
        .prepare(`SELECT id FROM events WHERE recurrence_id = ? ORDER BY date_time DESC LIMIT 1`)
        .get(target.recurrence_id) as { id: string } | undefined;
      if (remaining) {
        db.prepare(`UPDATE events SET recurrence_until = ? WHERE id = ?`).run(target.date_time, remaining.id);
      }
    }
  });
  del();

  return new NextResponse(null, { status: 204 });
}
